// Builds the retrieval evaluation samples (no API call, nothing changed in the database).
//
//   npx tsx scripts/eval-sample.ts --case-id <id> --witness <name> [--deposition <id>]
//
// 1. Candidate pairs: 20 found only by Path A, 20 only by Path B, 20 by both, each set split by its
//    own rank into high / medium / low thirds and sampled evenly within each (7 / 7 / 6), so the
//    same database state always gives the same sample.
// 2. Source exchanges: 20 exchanges of the deposition, evenly spaced through it, with every pair
//    either path retrieved for them, for reviewers to look for related testimony neither path found.
//
// Writes data/eval/retrieval-sample-v1.json (references, ranks, signals and empty evaluation fields;
// no transcript text) and data/eval/review/*.csv (the same, with the testimony, for reading; not
// committed, regenerated by this script).

import "dotenv/config";
import { mkdirSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { and, asc, eq, inArray } from "drizzle-orm";
import { EXTRACTOR_VERSION } from "../server/src/claims";
import { connect, type Database } from "../server/src/db/client";
import { claims, depositions, exchangeLines, exchanges, lines } from "../server/src/db/schema";
import { PARSER_VERSION } from "../server/src/ingest";
import { findPathA, findPathB, mergeCandidates, proceduralReason, type Candidate } from "../server/src/retrieve";
import { resolveDeposition, resolveWitness } from "./cases";

const PER_GROUP = 20;
const STRATA = [7, 7, 6]; // high, medium, low thirds of each group's own ranking
const SOURCE_EXCHANGES = 20;
const PATH_B_MODE = "rare_terms" as const;
const EVALUATION_FIELDS = {
  correctAttribution: null,
  sameProposition: null,
  potentialContradiction: null,
  compatible: null,
  insufficientContext: null,
  worthLawyerReview: null,
  note: "",
};

// `count` items spread evenly through `items` (first and last included when count > 1).
export function evenly<T>(items: readonly T[], count: number): T[] {
  if (items.length <= count) return [...items];
  if (count === 1) return [items[Math.floor(items.length / 2)]];
  return Array.from({ length: count }, (_, i) => items[Math.round((i * (items.length - 1)) / (count - 1))]);
}

// High, medium and low thirds of a ranked list, sampled evenly within each.
function stratified<T>(ranked: readonly T[]): { stratum: string; item: T }[] {
  const third = Math.ceil(ranked.length / 3);
  return ["high", "medium", "low"].flatMap((stratum, i) =>
    evenly(ranked.slice(i * third, (i + 1) * third), STRATA[i]).map((item) => ({ stratum, item })),
  );
}

const csv = (v: unknown) => `"${String(v ?? "").replace(/"/g, '""')}"`;

async function partText(db: Database, partIds: number[]) {
  const rows = partIds.length
    ? await db
        .select({ part: exchangeLines.exchangeId, page: lines.printedPage, line: lines.lineNo, text: lines.rawText })
        .from(exchangeLines)
        .innerJoin(lines, eq(lines.id, exchangeLines.lineId))
        .where(inArray(exchangeLines.exchangeId, partIds))
        .orderBy(asc(lines.printedPage), asc(lines.lineNo))
    : [];
  const byPart = new Map<number, typeof rows>();
  for (const r of rows) byPart.set(r.part, [...(byPart.get(r.part) ?? []), r]);
  return (id: number) => {
    const own = byPart.get(id) ?? [];
    return {
      first: own[0] ? { page: own[0].page, line: own[0].line } : null,
      last: own.at(-1) ? { page: own.at(-1)!.page, line: own.at(-1)!.line } : null,
      text: own.map((l) => `${l.page}:${l.line} ${l.text}`).join("\n"),
    };
  };
}

async function main() {
  const { values } = parseArgs({ options: { "case-id": { type: "string" }, witness: { type: "string" }, deposition: { type: "string" } } });
  const { db, pool } = connect();
  try {
    const target = await resolveWitness(db, { caseId: values["case-id"] ? Number(values["case-id"]) : undefined, witnessName: values.witness ?? "" });
    const depositionId = await resolveDeposition(db, target, values.deposition ? Number(values.deposition) : undefined);
    const docs = await db.select({ id: depositions.id, sha: depositions.fileSha256 }).from(depositions).where(eq(depositions.witnessId, target.witnessId));
    const alias = new Map(docs.map((d) => [d.id, d.sha.slice(0, 12)]));

    const pathA = await findPathA(db, { witnessId: target.witnessId, depositionId, extractorVersion: EXTRACTOR_VERSION });
    const pathB = await findPathB(db, { witnessId: target.witnessId, depositionId, mode: PATH_B_MODE });
    const merged = mergeCandidates({ claims: pathA, fulltext: pathB.pairs });
    const groups = {
      path_a_only: merged.filter((c) => c.sources.length === 1 && c.sources[0] === "claims").sort((x, y) => x.ranks.claims! - y.ranks.claims!),
      path_b_only: merged.filter((c) => c.sources.length === 1 && c.sources[0] === "fulltext").sort((x, y) => x.ranks.fulltext! - y.ranks.fulltext!),
      both: merged.filter((c) => c.sources.length === 2).sort((x, y) => x.rank - y.rank),
    };
    const picked = Object.entries(groups).flatMap(([group, list]) =>
      stratified(list).slice(0, PER_GROUP).map(({ stratum, item }) => ({ group, stratum, c: item, groupSize: list.length })),
    );

    const partIds = [...new Set(picked.flatMap(({ c }) => c.evidence.flatMap((e) => [e.exchangeA, e.exchangeB])))];
    const text = await partText(db, partIds);
    const claimIds = picked.flatMap(({ c }) => c.evidence.flatMap((e) => (e.path === "claims" ? [e.claimA, e.claimB] : [])));
    const claimRows = new Map((claimIds.length ? await db.select().from(claims).where(inArray(claims.id, claimIds)) : []).map((r) => [r.id, r]));

    const side = (c: Candidate, which: "a" | "b") => {
      const parts = [...new Set(c.evidence.map((e) => (which === "a" ? e.exchangeA : e.exchangeB)))];
      const logical = which === "a" ? c.a : c.b;
      return { document: alias.get(logical.depositionId)!, depositionId: logical.depositionId, group: logical.groupId, parts: parts.map((p) => ({ part: p, first: text(p).first, last: text(p).last })) };
    };
    const pairs = picked.map(({ group, stratum, c, groupSize }, i) => {
      const claimEv = c.evidence.find((e) => e.path === "claims");
      const fullEv = c.evidence.find((e) => e.path === "fulltext");
      return {
        id: `P${String(i + 1).padStart(2, "0")}`,
        group,
        stratum,
        groupSize,
        ranks: { merged: c.rank, ...c.ranks },
        a: side(c, "a"),
        b: side(c, "b"),
        pathA: claimEv && claimEv.path === "claims" ? { signal: claimEv.signal, predicate: claimEv.predicate, sharedEntities: claimEv.sharedEntities, claimA: claimEv.claimA, claimB: claimEv.claimB } : null,
        pathB: fullEv && fullEv.path === "fulltext" ? { score: Number(fullEv.score.toFixed(4)), sharedTerms: fullEv.sharedTerms } : null,
        evaluation: { ...EVALUATION_FIELDS },
      };
    });

    // Source exchanges: logical exchanges of the deposition, testimony only, evenly spaced.
    const own = await db
      .select({ id: exchanges.id, groupId: exchanges.groupId, kind: exchanges.kind, questionText: exchanges.questionText })
      .from(exchanges)
      .where(and(eq(exchanges.depositionId, depositionId), eq(exchanges.partNo, 1)))
      .orderBy(asc(exchanges.groupId));
    const testimony = own.filter((e) => proceduralReason(e) === null);
    const sources = evenly(testimony, SOURCE_EXCHANGES).map((e, i) => {
      const retrieved = merged.filter((c) => (c.a.depositionId === depositionId && c.a.groupId === e.groupId) || (c.b.depositionId === depositionId && c.b.groupId === e.groupId));
      return {
        id: `S${String(i + 1).padStart(2, "0")}`,
        document: alias.get(depositionId)!,
        group: e.groupId,
        part: e.id,
        retrieved: retrieved.map((c) => {
          const other = c.a.depositionId === depositionId ? c.b : c.a;
          return { group: other.groupId, depositionId: other.depositionId, sources: c.sources, mergedRank: c.rank };
        }),
        review: { relatedTestimonyFound: [] as string[], note: "" },
      };
    });
    const sourceText = await partText(db, sources.map((s) => s.part));
    const retrievedParts = [...new Set(merged.flatMap((c) => c.evidence.flatMap((e) => [e.exchangeA, e.exchangeB])))];
    const partGroup = new Map(
      (retrievedParts.length ? await db.select({ id: exchanges.id, d: exchanges.depositionId, g: exchanges.groupId }).from(exchanges).where(inArray(exchanges.id, retrievedParts)) : []).map((r) => [`${r.d}:${r.g}`, r.id]),
    );
    const retrievedText = await partText(db, sources.flatMap((s) => s.retrieved.map((r) => partGroup.get(`${r.depositionId}:${r.group}`) ?? -1)).filter((id) => id > 0));

    const sample = {
      version: 1,
      about:
        "Retrieval evaluation sample: candidate pairs from both paths for manual judgement, and source exchanges for finding related testimony neither path retrieved. References only; the review CSVs carry the text. Evaluation fields are null until reviewed (true / false / 'unsure').",
      generatedFrom: { extractorVersion: EXTRACTOR_VERSION, parserVersion: PARSER_VERSION, pathBMode: PATH_B_MODE, depositionId, mergedCandidates: merged.length, groups: Object.fromEntries(Object.entries(groups).map(([g, l]) => [g, l.length])) },
      documents: Object.fromEntries(docs.map((d) => [d.sha.slice(0, 12), d.sha])),
      fields: {
        correctAttribution: "Both statements are the witness's own (or a question he plainly adopted), as cited.",
        sameProposition: "Both are about the same proposition or event.",
        potentialContradiction: "They could conflict as stated; to be adjudicated.",
        compatible: "Both can be true together.",
        insufficientContext: "Can't tell without more surrounding testimony.",
        worthLawyerReview: "A lawyer preparing cross-examination would want to see this pair.",
      },
      pairs,
      sourceExchanges: sources,
    };
    mkdirSync("data/eval/review", { recursive: true });
    writeFileSync("data/eval/retrieval-sample-v1.json", `${JSON.stringify(sample, null, 2)}\n`);

    const head = ["id", "group", "stratum", "merged_rank", "path_a_rank", "path_b_rank", "path_a_signal", "path_b_terms", "a_ref", "a_text", "b_ref", "b_text", ...Object.keys(EVALUATION_FIELDS)];
    const ref = (s: ReturnType<typeof side>) => s.parts.map((p) => `${s.document} ${p.first?.page}:${p.first?.line}-${p.last?.page}:${p.last?.line} (part ${p.part})`).join("; ");
    const body = pairs.map((p) => {
      const sig = p.pathA ? `${p.pathA.signal} [${p.pathA.predicate}] ${p.pathA.sharedEntities.join(", ") || "(object overlap)"}: "${claimRows.get(p.pathA.claimA)?.keyPhrase}" / "${claimRows.get(p.pathA.claimB)?.keyPhrase}"` : "";
      return [p.id, p.group, p.stratum, p.ranks.merged, p.ranks.claims ?? "", p.ranks.fulltext ?? "", sig, p.pathB?.sharedTerms.join(", ") ?? "", ref(p.a), p.a.parts.map((x) => text(x.part).text).join("\n---\n"), ref(p.b), p.b.parts.map((x) => text(x.part).text).join("\n---\n"), "", "", "", "", "", "", ""].map(csv).join(",");
    });
    writeFileSync("data/eval/review/retrieval-pairs-v1.csv", `${head.join(",")}\n${body.join("\n")}\n`);

    const sHead = ["id", "ref", "text", "retrieved_count", "retrieved", "related_testimony_found", "note"];
    const sBody = sources.map((s) => {
      const t = sourceText(s.part);
      const got = s.retrieved
        .map((r) => {
          const pid = partGroup.get(`${r.depositionId}:${r.group}`);
          const rt = pid ? retrievedText(pid) : null;
          return `[${r.sources.join("+")}, merged rank ${r.mergedRank}] ${rt?.first?.page}:${rt?.first?.line}-${rt?.last?.page}:${rt?.last?.line} ${rt?.text.split("\n").slice(0, 2).join(" ").slice(0, 160) ?? ""}`;
        })
        .join("\n");
      return [s.id, `${s.document} ${t.first?.page}:${t.first?.line}-${t.last?.page}:${t.last?.line} (part ${s.part})`, t.text, s.retrieved.length, got, "", ""].map(csv).join(",");
    });
    writeFileSync("data/eval/review/source-exchanges-v1.csv", `${sHead.join(",")}\n${sBody.join("\n")}\n`);
    console.log(`Wrote ${pairs.length} pairs and ${sources.length} source exchanges. Groups: ${JSON.stringify(sample.generatedFrom.groups)}`);
  } finally {
    await pool.end();
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
